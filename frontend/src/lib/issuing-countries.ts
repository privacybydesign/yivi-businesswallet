// The codes ICAO adds for organisations and for the nationality variants of a
// British passport. No region names them, so the editor holds their copy.
const ICAO_ONLY_CODES = [
  "EUE",
  "GBD",
  "GBN",
  "GBO",
  "GBP",
  "GBS",
  "UNA",
  "UNK",
  "UNO",
  "XCC",
  "XES",
  "XMP",
  "XOM",
  "XPO",
] as const;
type IcaoOnlyCode = (typeof ICAO_ONLY_CODES)[number];

function isIcaoOnly(code: string): code is IcaoOnlyCode {
  return (ICAO_ONLY_CODES as readonly string[]).includes(code);
}

interface CountryChoice {
  code: string;
  name: string;
}

// The name of an issuing state in the locale. A code the list does not hold,
// from a stored flow, shows as it is.
function nameIn(code: string, names: Intl.DisplayNames, t: TFunction): string {
  if (isIcaoOnly(code)) {
    return t(`identityProofingFlows.editor.countries.${code}`);
  }
  const region = COUNTRY_REGIONS[code];
  return (region !== undefined && names.of(region)) || code;
}

// One per locale: the editor names each picked country on every render.
const regionNamesByLocale = new Map<string, Intl.DisplayNames>();

function regionNames(locale: string): Intl.DisplayNames {
  const cached = regionNamesByLocale.get(locale);
  if (cached !== undefined) {
    return cached;
  }

  const names = new Intl.DisplayNames([locale], { type: "region" });
  regionNamesByLocale.set(locale, names);
  return names;
}

export function issuingCountryName(
  code: string,
  locale: string,
  t: TFunction,
): string {
  return nameIn(code, regionNames(locale), t);
}

// Every issuing state, by name in the locale.
export function issuingCountryChoices(
  locale: string,
  t: TFunction,
): CountryChoice[] {
  const names = regionNames(locale);
  const codes = [...Object.keys(COUNTRY_REGIONS), ...ICAO_ONLY_CODES];
  const collator = new Intl.Collator(locale);
  return codes
    .map((code) => ({ code, name: nameIn(code, names, t) }))
    .sort((a, b) => collator.compare(a.name, b.name));
}
